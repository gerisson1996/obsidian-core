struct BakedFontData {
    SDL_Texture* texture = nullptr;
    stbtt_bakedchar cdata[224]; // Codepoints 32 .. 255 (ASCII + Latin-1 para português)
    int atlas_w = 512;
    int atlas_h = 512;
    float pixel_height = 20.0f;
    int line_height = 24;
};

static BakedFontData s_fonts[FONT_SIZE_COUNT];
static bool s_ttf_ready = false;
static bool s_pl_initialized = false;

static const float FONT_PIXEL_SIZES[FONT_SIZE_COUNT] = {
    16.0f,  // FONT_SIZE_SMALL
    22.0f,  // FONT_SIZE_MEDIUM
    30.0f,  // FONT_SIZE_LARGE
    40.0f   // FONT_SIZE_TITLE
};

static const int FONT_ATLAS_SIZES[FONT_SIZE_COUNT] = {
    512,    // 512x512
    512,    // 512x512
    1024,   // 1024x1024
    1024    // 1024x1024
};

bool FontRenderer::init(SDL_Renderer* renderer) {
    if (s_ttf_ready) return true;

    const unsigned char* font_buffer = nullptr;
    size_t font_size = 0;

#ifdef __SWITCH__
    Result rc = plInitialize(PlServiceType_User);
    if (R_SUCCEEDED(rc)) {
        s_pl_initialized = true;
        PlFontData pl_font;
        rc = plGetSharedFontByType(&pl_font, PlSharedFontType_Standard);
        if (R_SUCCEEDED(rc) && pl_font.address != nullptr && pl_font.size > 0) {
            font_buffer = reinterpret_cast<const unsigned char*>(pl_font.address);
            font_size = pl_font.size;
        }
    }
#endif

    if (!font_buffer) {
        // Fallback silencioso para fonte 8x8 caso não esteja rodando com shared fonts
        return false;
    }

    for (int i = 0; i < FONT_SIZE_COUNT; i++) {
        int aw = FONT_ATLAS_SIZES[i];
        int ah = FONT_ATLAS_SIZES[i];
        float px_h = FONT_PIXEL_SIZES[i];

        std::vector<unsigned char> mono_bitmap(aw * ah, 0);

        // Bake caracteres 32 a 255 (224 caracteres, engloba ASCII + todos os acentos PT-BR Latin-1)
        int res = stbtt_BakeFontBitmap(font_buffer, 0, px_h, mono_bitmap.data(), aw, ah, 32, 224, s_fonts[i].cdata);
        if (res <= 0) {
            continue; // Se não couber, segue
        }

        // Converte escala de cinza/alpha (1 byte) para RGBA32 (4 bytes branco com alpha)
        std::vector<uint32_t> rgba_pixels(aw * ah);
        for (int p = 0; p < aw * ah; p++) {
            uint8_t a = mono_bitmap[p];
            // RGBA: White color (0xFFFFFF) com canal Alpha modulado
            rgba_pixels[p] = (static_cast<uint32_t>(a) << 24) | 0x00FFFFFF;
        }

        SDL_Surface* surface = SDL_CreateRGBSurfaceWithFormatFrom(
            rgba_pixels.data(), aw, ah, 32, aw * 4, SDL_PIXELFORMAT_RGBA32);
        if (surface) {
            SDL_Texture* tex = SDL_CreateTextureFromSurface(renderer, surface);
            SDL_FreeSurface(surface);
            if (tex) {
                SDL_SetTextureBlendMode(tex, SDL_BLENDMODE_BLEND);
                s_fonts[i].texture = tex;
                s_fonts[i].atlas_w = aw;
                s_fonts[i].atlas_h = ah;
                s_fonts[i].pixel_height = px_h;
                s_fonts[i].line_height = static_cast<int>(px_h * 1.25f);
            }
        }
    }

    s_ttf_ready = (s_fonts[FONT_SIZE_MEDIUM].texture != nullptr);
    return s_ttf_ready;
}

void FontRenderer::cleanup() {
    for (int i = 0; i < FONT_SIZE_COUNT; i++) {
        if (s_fonts[i].texture) {
            SDL_DestroyTexture(s_fonts[i].texture);
            s_fonts[i].texture = nullptr;
        }
    }
    s_ttf_ready = false;

#ifdef __SWITCH__
    if (s_pl_initialized) {
        plExit();
        s_pl_initialized = false;
    }
#endif
}

bool FontRenderer::isTtfLoaded() {
    return s_ttf_ready;
}

static inline int scaleToFontIndex(int scale) {
    if (scale <= 1) return FONT_SIZE_SMALL;
    if (scale == 2) return FONT_SIZE_MEDIUM;
    if (scale == 3) return FONT_SIZE_LARGE;
    return FONT_SIZE_TITLE;
}

// Converte caractere ou sequência UTF-8 em codepoint Latin-1 (32..255)
static inline int decodeUtf8Latin1(const std::string& text, size_t& i) {
    unsigned char c = static_cast<unsigned char>(text[i]);
    if (c < 0x80) {
        return c;
    }

    if (c == 0xC3 && i + 1 < text.size()) {
        unsigned char next = static_cast<unsigned char>(text[++i]);
        return next + 0x40; // Mapeia diretamente UTF-8 de Latin-1 (0xC3 0xXX -> 0xXX + 64)
    } else if (c == 0xC2 && i + 1 < text.size()) {
        unsigned char next = static_cast<unsigned char>(text[++i]);
        return next;
    }

    return '?';
}

void FontRenderer::drawChar(SDL_Renderer* renderer, int x, int y, char c, SDL_Color color, int scale) {
    std::string s(1, c);
    drawText(renderer, x, y, s, color, scale);
}

void FontRenderer::drawText(SDL_Renderer* renderer, int x, int y, const std::string& text, SDL_Color color, int scale) {
    int font_idx = scaleToFontIndex(scale);
    BakedFontData& font = s_fonts[font_idx];

    // Se a fonte TrueType do Switch estiver pronta, desenha renderização suave anti-aliased
    if (s_ttf_ready && font.texture) {
        SDL_SetTextureColorMod(font.texture, color.r, color.g, color.b);
        SDL_SetTextureAlphaMod(font.texture, color.a);

        float cur_x = static_cast<float>(x);
        float cur_y = static_cast<float>(y + font.pixel_height * 0.88f); // Base-line

        for (size_t i = 0; i < text.size(); i++) {
            if (text[i] == '\n') {
                cur_x = static_cast<float>(x);
                cur_y += font.line_height;
                continue;
            }

            int codepoint = decodeUtf8Latin1(text, i);
            if (codepoint < 32 || codepoint > 255) {
                codepoint = '?';
            }

            stbtt_aligned_quad q;
            stbtt_GetBakedQuad(font.cdata, font.atlas_w, font.atlas_h, codepoint - 32, &cur_x, &cur_y, &q, 0);

            SDL_Rect src = {
                static_cast<int>(q.s0 * font.atlas_w),
                static_cast<int>(q.t0 * font.atlas_h),
                static_cast<int>((q.s1 - q.s0) * font.atlas_w),
                static_cast<int>((q.t1 - q.t0) * font.atlas_h)
            };
            SDL_Rect dst = {
                static_cast<int>(q.x0),
                static_cast<int>(q.y0),
                static_cast<int>(q.x1 - q.x0),
                static_cast<int>(q.y1 - q.y0)
            };

            SDL_RenderCopy(renderer, font.texture, &src, &dst);
        }
        return;
    }

    // Fallback para fonte 8x8 caso TTF não esteja disponível
    int cur_x = x;
    int cur_y = y;

    for (size_t i = 0; i < text.size(); i++) {
        unsigned char c = text[i];
        if (c == '\n') {
            cur_x = x;
            cur_y += 10 * scale;
            continue;
        }

        if (c == 0xC3 && i + 1 < text.size()) {
            unsigned char next = text[++i];
            char mapped = '?';
            switch (next) {
                case 0xA1: case 0xA0: case 0xA2: case 0xA3: mapped = 'a'; break;
                case 0x81: case 0x80: case 0x82: case 0x83: mapped = 'A'; break;
                case 0xA9: case 0xAA: mapped = 'e'; break;
                case 0x89: case 0x8A: mapped = 'E'; break;
                case 0xAD: mapped = 'i'; break;
                case 0x8D: mapped = 'I'; break;
                case 0xB3: case 0xB4: case 0xB5: mapped = 'o'; break;
                case 0x93: case 0x94: case 0x95: mapped = 'O'; break;
                case 0xBA: case 0xBC: mapped = 'u'; break;
                case 0x9A: case 0x9C: mapped = 'U'; break;
                case 0xA7: mapped = 'c'; break;
                case 0x87: mapped = 'C'; break;
                default: mapped = '?'; break;
            }
            c = mapped;
        }

        if (c >= 128) c = '?';
        SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
        const uint8_t* glyph = font8x8_fallback[c];

        for (int row = 0; row < 8; row++) {
            uint8_t line = glyph[row];
            for (int col = 0; col < 8; col++) {
                if ((line >> (7 - col)) & 1) {
                    SDL_Rect r = { cur_x + col * scale, cur_y + row * scale, scale, scale };
                    SDL_RenderFillRect(renderer, &r);
                }
            }
        }
        cur_x += 8 * scale;
    }
}

int FontRenderer::getTextWidth(const std::string& text, int scale) {
    int font_idx = scaleToFontIndex(scale);
    BakedFontData& font = s_fonts[font_idx];

    if (s_ttf_ready && font.texture) {
        float max_w = 0.0f;
        float cur_w = 0.0f;

        for (size_t i = 0; i < text.size(); i++) {
            if (text[i] == '\n') {
                if (cur_w > max_w) max_w = cur_w;
                cur_w = 0.0f;
                continue;
            }

            int codepoint = decodeUtf8Latin1(text, i);
            if (codepoint < 32 || codepoint > 255) codepoint = '?';

            cur_w += font.cdata[codepoint - 32].xadvance;
        }
        if (cur_w > max_w) max_w = cur_w;
        return static_cast<int>(max_w);
    }

    // Fallback 8x8
    int max_w = 0;
    int cur_w = 0;
    for (size_t i = 0; i < text.size(); i++) {
        if (text[i] == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
        } else if (static_cast<unsigned char>(text[i]) == 0xC3 && i + 1 < text.size()) {
            i++;
            cur_w += 8 * scale;
        } else {
            cur_w += 8 * scale;
        }
    }
    return (cur_w > max_w) ? cur_w : max_w;
}


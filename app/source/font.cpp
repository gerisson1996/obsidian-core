void FontRenderer::drawChar(SDL_Renderer* renderer, int x, int y, char c, SDL_Color color, int scale) {
    unsigned char uc = static_cast<unsigned char>(c);
    if (uc >= 128) uc = '?';

    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    const uint8_t* glyph = font8x8_basic[uc];

    for (int row = 0; row < 8; row++) {
        uint8_t line = glyph[row];
        for (int col = 0; col < 8; col++) {
            if ((line >> (7 - col)) & 1) {
                SDL_Rect r = { x + col * scale, y + row * scale, scale, scale };
                SDL_RenderFillRect(renderer, &r);
            }
        }
    }
}

void FontRenderer::drawText(SDL_Renderer* renderer, int x, int y, const std::string& text, SDL_Color color, int scale) {
    int cur_x = x;
    int cur_y = y;

    for (size_t i = 0; i < text.size(); i++) {
        unsigned char c = text[i];
        if (c == '\n') {
            cur_x = x;
            cur_y += 10 * scale;
            continue;
        }

        // Mapeamento de UTF-8 em portugues
        if (c == 0xC3 && i + 1 < text.size()) {
            unsigned char next = text[++i];
            char mapped = '?';
            switch (next) {
                case 0xA1: case 0xA0: case 0xA2: case 0xA3: mapped = 'a'; break; // a
                case 0x81: case 0x80: case 0x82: case 0x83: mapped = 'A'; break; // A
                case 0xA9: case 0xAA: mapped = 'e'; break; // e
                case 0x89: case 0x8A: mapped = 'E'; break; // E
                case 0xAD: mapped = 'i'; break; // i
                case 0x8D: mapped = 'I'; break; // I
                case 0xB3: case 0xB4: case 0xB5: mapped = 'o'; break; // o
                case 0x93: case 0x94: case 0x95: mapped = 'O'; break; // O
                case 0xBA: case 0xBC: mapped = 'u'; break; // u
                case 0x9A: case 0x9C: mapped = 'U'; break; // U
                case 0xA7: mapped = 'c'; break; // c
                case 0x87: mapped = 'C'; break; // C
                default: mapped = '?'; break;
            }
            drawChar(renderer, cur_x, cur_y, mapped, color, scale);
            cur_x += 8 * scale;
            continue;
        }

        drawChar(renderer, cur_x, cur_y, c, color, scale);
        cur_x += 8 * scale;
    }
}

int FontRenderer::getTextWidth(const std::string& text, int scale) {
    int max_w = 0;
    int cur_w = 0;
    for (size_t i = 0; i < text.size(); i++) {
        if (text[i] == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
        } else if (static_cast<unsigned char>(text[i]) == 0xC3 && i + 1 < text.size()) {
            i++;
            cur_w += 8 * scale;
        } else {
            cur_w += 8 * scale;
        }
    }
    return (cur_w > max_w) ? cur_w : max_w;
}

int FontRenderer::getTextHeight(int scale) {
    return 10 * scale;
}
